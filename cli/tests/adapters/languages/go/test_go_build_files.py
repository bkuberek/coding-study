import json
import shutil
import subprocess
from pathlib import Path

import pytest

from coding_study.adapters.languages.go.build_files import (
    GoPackage,
    ThunkFile,
    build_diagnostics,
    main_source,
    output_text,
    overlay_document,
    package_clause,
    registration_source,
    thunk_source,
)
from coding_study.domain.signature import ClassSignature
from tests.stub_contract import STUB_CASES

BUILD = Path("/ws/.cs/build/go")
USER = GoPackage(
    "user",
    "workspace/practice/two_sum",
    "two_sum",
    "twoSum",
    BUILD / "gen/two_sum/user_targets.go",
)
REFERENCE = GoPackage(
    "ref/hash-map",
    "csbuild/ref/two_sum/hash_map",
    "two_sum",
    "twoSum",
    BUILD / "ref/two_sum/hash_map/zz_cs_targets.go",
)
CLASS_CASES = [case for case in STUB_CASES if isinstance(case.meta.signature, ClassSignature)]
RECORDED = Path(__file__).parent / "recorded"
"""`go build -json` output (Go 1.27) recorded in a workspace's .cs/build/go."""
MISNAMED = (RECORDED / "misnamed.jsonl").read_text()
TYPE_ERRORS = (RECORDED / "type-errors.jsonl").read_text()


def test_reads_the_package_clause_after_comments():
    source = "// Two Sum. Run: cstudy test two-sum\n\npackage two_sum\n\nfunc twoSum() {}\n"
    assert package_clause(source, "fallback") == "two_sum"


def test_a_file_without_a_package_clause_gets_the_default():
    assert package_clause("", "two_sum") == "two_sum"


def test_registration_maps_the_symbol_to_itself():
    assert registration_source(USER, available=True) == (
        "// Code generated by cstudy; DO NOT EDIT.\n\npackage two_sum\n\n"
        'var CsTargets = map[string]any{\n\t"twoSum": twoSum,\n}\n'
    )


def test_an_unavailable_registration_is_empty():
    assert "var CsTargets = map[string]any{\n}\n" in registration_source(USER, available=False)


def test_main_registers_every_package_by_target_id():
    main = main_source([USER, REFERENCE], {})
    assert '\tt0 "workspace/practice/two_sum"\n\tt1 "csbuild/ref/two_sum/hash_map"\n' in main
    assert '"ref/hash-map": t1.CsTargets,' in main
    assert "}, nil, nil)" in main


def test_main_says_why_a_target_is_unavailable():
    main = main_source([USER], {"user": 'undefined: "twoSum"'})
    assert 'runner.Unavailable{\n\t\t"user": {"twoSum": "undefined: \\"twoSum\\""},\n\t}' in main


def test_overlay_maps_the_virtual_file_to_the_generated_one():
    virtual = Path("/ws/go/practice/two_sum/zz_cs_targets.go")
    document = json.loads(overlay_document({virtual: USER.registration}))
    assert document == {"Replace": {str(virtual): str(USER.registration)}}


def test_diagnostics_resolve_paths_against_the_build_directory():
    (diagnostic,) = build_diagnostics(MISNAMED, "", BUILD)
    assert (diagnostic.path, diagnostic.position, diagnostic.message) == (
        BUILD / "gen/two_sum/user_targets.go",
        "6:12",
        "undefined: twoSum",
    )


def test_diagnostics_keep_their_indented_lines():
    diagnostics = build_diagnostics(TYPE_ERRORS, "", BUILD)
    assert diagnostics[1].shown("go/practice/two_sum/two_sum.go") == (
        "go/practice/two_sum/two_sum.go:6:9: cannot use x (variable of type int) as []int value "
        "in return statement",
        "\thave (int)",
        "\twant ([]int)",
    )


def test_diagnostics_include_text_on_standard_error():
    (diagnostic,) = build_diagnostics("", "main.go:3:8: package nosuchpkg is not in std\n", BUILD)
    assert diagnostic.path == BUILD / "main.go"


def test_output_text_is_everything_go_build_said():
    assert output_text(MISNAMED, "go: oops\n")[-1] == "go: oops"


def thunks_of(case_name: str) -> ThunkFile:
    case = next(case for case in STUB_CASES if case.name == case_name)
    assert isinstance(case.meta.signature, ClassSignature)
    return ThunkFile(BUILD / "gen" / case.meta.snake_slug / "zz_cs_thunks.go", case.meta.signature)


def thunk_text(case_name: str, available: bool = True) -> str:
    case = next(case for case in STUB_CASES if case.name == case_name)
    return thunk_source(thunks_of(case_name), case.meta.snake_slug, available)


def test_thunks_call_each_method_with_asserted_arguments_and_return_the_result():
    assert thunk_text("lru-cache") == (
        "// Code generated by cstudy; DO NOT EDIT.\n\npackage lru_cache\n\n"
        "var CsThunks = struct {\n\tReceiver any\n\tMethods  map[string]func(any, []any) any\n}{\n"
        "\tReceiver: (*LRUCache)(nil),\n"
        "\tMethods: map[string]func(any, []any) any{\n"
        '\t\t"Get": func(r any, a []any) any {\n'
        "\t\t\treturn r.(*LRUCache).Get(a[0].(int))\n\t\t},\n"
        '\t\t"Put": func(r any, a []any) any {\n'
        "\t\t\tr.(*LRUCache).Put(a[0].(int), a[1].(int))\n\t\t\treturn nil\n\t\t},\n"
        "\t},\n}\n"
    )


def test_a_method_without_a_result_returns_nil_and_one_with_a_result_returns_it():
    thunks = thunk_text("min-stack")
    assert "\t\t\tr.(*MinStack).Pop()\n\t\t\treturn nil\n" in thunks
    assert "\t\t\treturn r.(*MinStack).Top()\n" in thunks


def test_every_parameter_is_asserted_in_declared_order():
    thunks = thunk_text("progressive")
    assert ".Set(a[0].(int64), a[1].(string), a[2].(string), a[3].(string))\n" in thunks
    assert ".ScanByPrefix(a[0].(int64), a[1].(string), a[2].(string))\n" in thunks


def test_lists_and_arrays_assert_slices_and_nodes_are_the_support_types():
    thunks = thunk_text("conformance-types")
    assert "EchoIntListList(a[0].([][]int))" in thunks
    assert "EchoCharMatrix(a[0].([][]rune))" in thunks
    assert "EchoListNode(a[0].(*support.ListNode))" in thunks
    assert "EchoTreeNodeList(a[0].([]*support.TreeNode))" in thunks
    assert "EchoListNodeArray(a[0].([]*support.ListNode))" in thunks
    assert 'import "cstudy/support"\n' in thunks


def test_decimal_and_date_import_their_packages_in_goimports_groups():
    thunks = thunk_text("conformance-decimal-date-types")
    assert 'import (\n\t"time"\n\n\t"github.com/shopspring/decimal"\n)\n' in thunks
    assert "EchoDecimalMatrix(a[0].([][]decimal.Decimal))" in thunks
    assert "EchoDateList(a[0].([]time.Time))" in thunks


def test_only_the_types_a_thunk_asserts_are_imported():
    thunks = thunk_text("lru-cache")
    assert "import" not in thunks
    assert "support" not in thunk_text("conformance-decimal-date-types")


def test_thunk_names_are_the_exported_go_method_names():
    assert '\t\t"GetMin": func(r any, a []any) any {\n' in thunk_text("min-stack")


def test_unavailable_thunks_offer_none_and_import_nothing():
    assert thunk_text("conformance-decimal-date-types", available=False) == (
        "// Code generated by cstudy; DO NOT EDIT.\n\npackage conformance_decimal_date_types\n\n"
        "var CsThunks = struct {\n\tReceiver any\n\tMethods  map[string]func(any, []any) any\n}{}\n"
    )


def test_main_hands_the_thunks_of_the_packages_that_have_them_to_the_runner():
    with_thunks = GoPackage(
        "user",
        "workspace/practice/lru_cache",
        "lru_cache",
        "NewLRUCache",
        BUILD / "gen/lru_cache/user_targets.go",
        thunks_of("lru-cache"),
    )
    main = main_source([with_thunks, REFERENCE], {})
    assert '}, nil, runner.Thunks{\n\t\t"user": t0.CsThunks,\n\t})' in main
    assert "t1.CsThunks" not in main


@pytest.mark.skipif(shutil.which("gofmt") is None, reason="gofmt is not installed")
@pytest.mark.parametrize("available", [True, False])
@pytest.mark.parametrize("case", CLASS_CASES, ids=lambda case: case.name)
def test_thunk_files_are_gofmt_clean(case, available, tmp_path):
    path = tmp_path / "zz_cs_thunks.go"
    path.write_text(thunk_text(case.name, available))
    result = subprocess.run(["gofmt", "-l", str(path)], capture_output=True, text=True, check=True)
    assert result.stdout == ""

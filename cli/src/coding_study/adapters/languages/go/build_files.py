"""The generated Go build (docs/specs/runners.md#go-build-details): registration and thunk
files, the overlay, the main package, and the compiler diagnostics of `go build -json`.

Every compiled target (`user` or `ref/<approach>`) is a package with one generated registration
file, `var CsTargets = map[string]any{"twoSum": twoSum}`, so the runner can call the package's
unexported function by name. A class kind's package also gets a thunk file, one typed caller per
declared method, so the runner calls a method without reflection. The thunks assert the types of
the signature, so a method with another signature fails to compile in the thunk file only: the
build runs again with that file left empty and the runner calls through reflection, which
reports the mismatch. The user's generated files enter the user's package through
`go build -overlay`: nothing is written to the practice directory, and compiler errors and
breakpoints name the real files. The compiler names an overlaid file by its replacement path,
which is how its diagnostics are told apart from the user's.
"""

import json
import re
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass, replace
from pathlib import Path
from typing import cast

from coding_study.adapters.languages.go.stub_generator import (
    SUPPORT_NAME,
    go_type,
    import_lines,
)
from coding_study.domain.naming import NameRole, member_name
from coding_study.domain.problem import Language
from coding_study.domain.signature import ClassSignature, Method

GENERATED_HEADER = "// Code generated by cstudy; DO NOT EDIT."
REGISTRATION_FILE = "zz_cs_targets.go"
"""The registration's file name inside the target's package directory."""
REGISTRATION_VARIABLE = "CsTargets"
THUNK_FILE = "zz_cs_thunks.go"
"""The thunk file's name; the runner leaves the frames of this file out of traces."""
THUNKS_VARIABLE = "CsThunks"
RUNNER_PACKAGE = "cstudy/runner"
THIRD_PARTY_DIRECTORY = "third_party"
VENDORED_MODULES: Mapping[str, str] = {"github.com/shopspring/decimal": "v1.5.0"}
"""The modules a solution may import (`decimal`) at their vendored versions. Builds never
download, so each is a copy in the runner module's `third_party/`, reached through `replace`
(runners/go/third_party/README.md)."""
_PACKAGE_CLAUSE = re.compile(r"^package\s+([A-Za-z_][A-Za-z0-9_]*)", re.MULTILINE)
_DIAGNOSTIC = re.compile(
    r"^(?P<file>[^\s:][^:]*\.go):(?P<line>\d+)(?::(?P<column>\d+))?: (?P<message>.*)$"
)
_BUILD_OUTPUT = "build-output"


@dataclass(frozen=True, slots=True)
class ThunkFile:
    """The typed callers of a class's methods."""

    path: Path
    """The file as the compiler sees it: the overlay replacement for the user."""
    signature: ClassSignature


@dataclass(frozen=True, slots=True)
class GoPackage:
    """One package linked into the runner binary."""

    target_id: str
    """`user` or `ref/<approach>`, the id the request's `{"compiled": ...}` names."""
    import_path: str
    package: str
    """The package clause, which the registration file must repeat."""
    symbol: str
    """The function, or the constructor of a class kind, that the registration exposes."""
    registration: Path
    """The registration file as the compiler sees it: the overlay replacement for the user."""
    thunks: ThunkFile | None = None
    """None where the runner calls through reflection: functions and concurrent classes."""


@dataclass(frozen=True, slots=True)
class Diagnostic:
    path: Path
    """Resolved against the directory `go build` ran in."""
    position: str
    """`line:column`, or `line` alone."""
    message: str
    continuation: tuple[str, ...] = ()
    """The compiler's indented lines after it (`have ...`, `want ...`)."""

    def shown(self, path: str) -> tuple[str, ...]:
        """The diagnostic's lines with the file shown as `path`."""
        return (f"{path}:{self.position}: {self.message}", *self.continuation)


def vendored_path(module: str) -> str:
    """The copy of a vendored module, relative to the runner module."""
    return f"{THIRD_PARTY_DIRECTORY}/{module}"


def package_clause(source: str, default: str) -> str:
    """The name in the first `package` clause of a Go file, or `default` when there is none."""
    match = _PACKAGE_CLAUSE.search(source)
    return match.group(1) if match else default


def registration_source(target: GoPackage, available: bool) -> str:
    """The registration file; an unavailable symbol (pass 2) is left out of the map."""
    entry = f'\t"{target.symbol}": {target.symbol},\n' if available else ""
    return (
        f"{GENERATED_HEADER}\n\npackage {target.package}\n\n"
        f"var {REGISTRATION_VARIABLE} = map[string]any{{\n{entry}}}\n"
    )


def thunk_source(file: ThunkFile, package: str, available: bool) -> str:
    """The thunk file; without `available` (pass 2) it offers none, and the runner calls through
    reflection."""
    methods = file.signature.methods if available else ()
    imports = "".join(
        f"{line}\n" for line in import_lines(param.type for m in methods for param in m.params)
    )
    return (
        f"{GENERATED_HEADER}\n\npackage {package}\n{imports}\n"
        f"var {THUNKS_VARIABLE} = struct {{\n\tReceiver any\n"
        f"\tMethods  map[string]func(any, []any) any\n}}{_thunk_literal(file.signature, methods)}\n"
    )


def _thunk_literal(signature: ClassSignature, methods: Sequence[Method]) -> str:
    """The value of the thunks variable; `{}` when there are no methods to call."""
    if not methods:
        return "{}"
    entries = "".join(_thunk(signature, method) for method in methods)
    return (
        f"{{\n\tReceiver: (*{signature.name})(nil),\n"
        f"\tMethods: map[string]func(any, []any) any{{\n{entries}\t}},\n}}"
    )


def _thunk(signature: ClassSignature, method: Method) -> str:
    """One entry, which takes the arguments as the types the signature declares and returns the
    result as an any. Its body is always on lines of its own, which is how gofmt keeps it."""
    name = member_name(method.name, Language.GO, NameRole.METHOD)
    arguments = ", ".join(
        f"a[{index}].({go_type(param.type, SUPPORT_NAME)})"
        for index, param in enumerate(method.params)
    )
    call = f"r.(*{signature.name}).{name}({arguments})"
    body = [f"return {call}"] if go_type(method.returns.type) else [call, "return nil"]
    lines = "".join(f"\t\t\t{line}\n" for line in body)
    return f"\t\t{_go_string(name)}: func(r any, a []any) any {{\n{lines}\t\t}},\n"


def main_source(targets: Sequence[GoPackage], unavailable: Mapping[str, str]) -> str:
    """The runner binary's main package: every target's registration and thunks, and why the
    targets in `unavailable` (target id to compiler message) have no registration."""
    imports = "".join(f'\tt{index} "{t.import_path}"\n' for index, t in enumerate(targets))
    entries = "".join(
        f"\t\t{_go_string(t.target_id)}: t{index}.{REGISTRATION_VARIABLE},\n"
        for index, t in enumerate(targets)
    )
    reasons = _unavailable_literal(targets, unavailable)
    thunks = _thunks_literal(targets)
    return (
        f'{GENERATED_HEADER}\n\npackage main\n\nimport (\n\t"{RUNNER_PACKAGE}"\n\n{imports})\n\n'
        f"func main() {{\n\trunner.Main(runner.Registry{{\n{entries}\t}}, {reasons},"
        f" {thunks})\n}}\n"
    )


def _thunks_literal(targets: Sequence[GoPackage]) -> str:
    entries = "".join(
        f"\t\t{_go_string(t.target_id)}: t{index}.{THUNKS_VARIABLE},\n"
        for index, t in enumerate(targets)
        if t.thunks is not None
    )
    return f"runner.Thunks{{\n{entries}\t}}" if entries else "nil"


def _unavailable_literal(targets: Sequence[GoPackage], unavailable: Mapping[str, str]) -> str:
    if not unavailable:
        return "nil"
    symbols = {target.target_id: target.symbol for target in targets}
    entries = "".join(
        f"\t\t{_go_string(target_id)}: {{{_go_string(symbols[target_id])}: {_go_string(why)}}},\n"
        for target_id, why in unavailable.items()
    )
    return f"runner.Unavailable{{\n{entries}\t}}"


def _go_string(text: str) -> str:
    """A Go interpreted string literal; JSON escapes are valid Go escapes."""
    return json.dumps(text)


def overlay_document(replacements: Mapping[Path, Path]) -> str:
    """`go build -overlay`: each virtual file and the real file that stands in for it."""
    files = {str(virtual): str(real) for virtual, real in replacements.items()}
    return json.dumps({"Replace": files}, indent=2) + "\n"


def build_diagnostics(stdout: str, stderr: str, cwd: Path) -> tuple[Diagnostic, ...]:
    """Compiler diagnostics from `go build -json`: the `build-output` events on standard output,
    and the package-loading errors that `go` prints as text on standard error."""
    output_lines = [*_build_output_lines(stdout), *stderr.splitlines()]
    diagnostics: list[Diagnostic] = []
    for line in output_lines:
        match = _DIAGNOSTIC.match(line)
        if match:
            path = (cwd / match["file"]).resolve()
            position = match["line"] + (f":{match['column']}" if match["column"] else "")
            diagnostics.append(Diagnostic(path, position, match["message"]))
        elif diagnostics and line.startswith("\t"):
            last = diagnostics[-1]
            diagnostics[-1] = replace(last, continuation=(*last.continuation, line))
    return tuple(diagnostics)


def _build_output_lines(stdout: str) -> Iterable[str]:
    for line in stdout.splitlines():
        if not line.startswith("{"):
            continue
        try:
            event: object = json.loads(line)
        except ValueError:
            continue
        if not isinstance(event, dict):
            continue
        fields = cast("dict[str, object]", event)
        output = fields.get("Output")
        if fields.get("Action") == _BUILD_OUTPUT and isinstance(output, str):
            yield from output.splitlines()


def output_text(stdout: str, stderr: str) -> tuple[str, ...]:
    """Everything `go build` said, for a failure that is not a compiler diagnostic."""
    return (*_build_output_lines(stdout), *stderr.splitlines())

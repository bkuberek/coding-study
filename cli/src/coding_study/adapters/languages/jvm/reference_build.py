"""The reference build in `.cs/build/jvm` (docs/specs/runners.md#reference-materialization).

It mirrors the workspace's `jvm/` project (same build files, same included runners `jvm/`) so
references compile exactly like user code, but into `ref.<snake_slug>.<approach_snake>` packages.
"""

import os
from collections.abc import Iterable
from pathlib import Path

from coding_study.application.ports import ReferenceSource
from coding_study.domain.layout import BUILD_DIRECTORY, jvm_reference_package, reference_build_path
from coding_study.domain.problem import Language, ProblemMeta

REFERENCE_PROJECT = f"{BUILD_DIRECTORY}/jvm"
MIRRORED_FILES = (
    "gradle.properties",
    "gradle/libs.versions.toml",
    "java/build.gradle.kts",
    "kotlin/build.gradle.kts",
)
SETTINGS_FILE = "settings.gradle.kts"
SETTINGS = """\
// Generated by cstudy for materialized references; mirrors the workspace's jvm/settings.gradle.kts.
pluginManagement {
    includeBuild("{runners}")
}

dependencyResolutionManagement {
    repositories {
        mavenCentral()
    }
}

rootProject.name = "coding-study-references"

includeBuild("{runners}")
include("java", "kotlin")
"""
"""`{runners}` is the runners' `jvm/` relative to the reference project."""


class ReferenceBuild:
    def __init__(self, root: Path, workspace: Path, runners: Path) -> None:
        """`root` is the workspace root, `workspace` its `jvm/` project and `runners` the
        runners' `jvm/` included build."""
        self._root = root
        self._workspace = workspace
        self._runners = runners

    @property
    def project_directory(self) -> Path:
        return self._root / REFERENCE_PROJECT

    def materialize(
        self, meta: ProblemMeta, sources: Iterable[ReferenceSource], language: Language
    ) -> None:
        """Copy each source with its package line; drop files of approaches not in `sources`."""
        self._write_build_files()
        targets = {
            self._root / reference_build_path(meta, source.approach_id, language): source
            for source in sources
        }
        for target, source in targets.items():
            _write_if_changed(target, _with_package(source, meta, language))
        for problem_directory in {target.parent.parent for target in targets}:
            _remove_stale(problem_directory, set(targets))

    def _write_build_files(self) -> None:
        for relative in MIRRORED_FILES:
            mirrored = self._workspace / relative
            _write_if_changed(
                self.project_directory / relative, mirrored.read_text(encoding="utf-8")
            )
        runners = Path(os.path.relpath(self._runners, self.project_directory)).as_posix()
        settings = SETTINGS.replace("{runners}", runners)
        _write_if_changed(self.project_directory / SETTINGS_FILE, settings)


def _with_package(source: ReferenceSource, meta: ProblemMeta, language: Language) -> str:
    terminator = ";" if language is Language.JAVA else ""
    package = jvm_reference_package(meta, source.approach_id)
    return f"package {package}{terminator}\n\n{source.path.read_text(encoding='utf-8')}"


def _write_if_changed(path: Path, text: str) -> None:
    """Unchanged files keep their timestamps, so Gradle's up-to-date checks stay cheap."""
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def _remove_stale(directory: Path, kept: set[Path]) -> None:
    for path in sorted(directory.rglob("*"), reverse=True):
        if path.is_file() and path not in kept:
            path.unlink()
        elif path.is_dir() and not any(path.iterdir()):
            path.rmdir()

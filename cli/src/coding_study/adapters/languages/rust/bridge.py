"""The generated Rust bridge (docs/specs/runners.md#rust-build-details).

Rust has no reflection, so each runner binary gets a `main.rs` generated from the signature. It
brings every compiled target (the user's file, each reference) in as a `#[path]` module, so
compiler errors, panics and breakpoints name the real file, and for each target it spells out
every argument's type, decodes it, calls the code and hands back the result for encoding.
Class kinds get a constructor function and a `match` on the operation name. A concurrent class
is shared by the worker threads of its stress runs: its methods take `&self`, every decoded call
is `Send`, and the constructor hands the instance to `cs_runner::shared`, whose `Send + Sync`
bound is where the compiler rejects a class that is not thread-safe. A project's entry class is
shared the same way from the level of its first stress case
(docs/specs/runners.md#stress-in-project-jobs), or of its first case that spawns a task.

A project on the virtual clock registers its class as `Entry::Clock`, and each operation's call
is a future the runner awaits on the case's runtime: an `async fn` is awaited inside it, any other
method called. An owned instance's call borrows it; a shared instance's call holds an `Arc` of
it, so `@spawn` can hand the call to `tokio::spawn`, and its result must be `Send`. The worker
threads of a shared class's stress runs call the same methods, blocking on an `async fn` on the
real clock (docs/specs/runners.md#virtual-clock-and-stress-in-project-jobs).

Because every type is spelled, a solution with another signature fails to compile in the bridge,
not in its own file. The bridge records which target owns each of its lines, so the runner can
build again without the targets whose bridge code did not compile and report a `load_error`
for each of them instead.
"""

from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field, replace
from pathlib import Path

from coding_study.adapters.languages.rust.types import (
    crate_imports,
    node_kinds,
    rust_name,
    rust_type,
)
from coding_study.domain.language_limits import LIST_IDENTITY, names_list_nodes
from coding_study.domain.naming import NameRole, member_name
from coding_study.domain.problem import Language, ProblemKind
from coding_study.domain.project import PATH_SEPARATOR, RUST_LIBRARY_ROOT
from coding_study.domain.signature import (
    ClassSignature,
    FunctionSignature,
    NodeSerialization,
    Param,
    Returns,
    Signature,
)

GENERATED_HEADER = "// Code generated by cstudy; DO NOT EDIT."
INDENT = "    "
UNSUPPORTED_TYPE = "UnsupportedType"
ARGUMENT_PREFIX = "arg_"
"""The bridge names each decoded argument `arg_<parameter>`."""
_IDENTITY_PREFIX = "nodes_of_"
SHARED_NODES_REASON = "rust does not support node types in concurrent problems: Rc is not Send"


@dataclass(frozen=True, slots=True)
class Unavailable:
    """Why a target cannot run; its jobs get this `load_error`."""

    error_type: str
    message: str


@dataclass(frozen=True, slots=True)
class BridgeTarget:
    """One compiled target of the runner binary."""

    target_id: str
    """`user` or `ref/<approach>`, the id the request's `{"compiled": ...}` names."""
    module: str
    """The module the bridge gives the file: `user` or `ref_<approach_snake>`."""
    file: Path
    unavailable: Unavailable | None = None
    with_module: bool = True
    """False when the module itself cannot be loaded (its file is missing)."""
    crate: bool = False
    """A project's crate, which the harness depends on as `module` instead of bringing a file in
    as a `#[path]` module: `file` is the crate's root directory, and every file under it is the
    target's (docs/specs/runners.md#rust-projects)."""

    @property
    def shown_name(self) -> str:
        """The file a message names for the target: a project crate's library root."""
        return RUST_LIBRARY_ROOT if self.crate else self.file.name

    @property
    def trace_file(self) -> str:
        """What `cs_runner::Target.file` holds: the file whose frames a trace keeps, or for a
        crate its directory with a final `/`, so the frames of every file under it are kept."""
        return f"{self.file}{PATH_SEPARATOR}" if self.crate else str(self.file)


@dataclass(frozen=True, slots=True)
class Bridge:
    text: str
    owners: Mapping[int, str]
    """1-based line number to the id of the target whose bridge code it is."""
    modules: Mapping[int, str]
    """1-based line number of each `mod` item to its target id."""


def bridge_source(
    signature: Signature,
    targets: Sequence[BridgeTarget],
    *,
    kind: ProblemKind,
    shared: bool = False,
    clock: bool = False,
) -> Bridge:
    """`shared`: a project's graded levels have stress cases, whose worker threads share its
    entry class, as a concurrent problem's class is shared, or spawn tasks, which share it too.
    `clock`: the project is on the virtual clock."""
    lines = _Lines()
    lines.add(None, GENERATED_HEADER, "#![allow(unused)]", "")
    lines.add(None, *_imports(signature))
    unsupported = unsupported_reason(signature, kind)
    for target in targets:
        if target.with_module and not target.crate:
            lines.add(None, "#[allow(warnings)]", f"#[path = {rust_string(str(target.file))}]")
            lines.module(target.target_id, f"mod {target.module};")
            lines.add(None, "")
    entries: list[tuple[BridgeTarget, str]] = []
    for target in targets:
        unavailable = target.unavailable or (
            Unavailable(UNSUPPORTED_TYPE, unsupported) if unsupported else None
        )
        if unavailable is not None:
            entries.append((target, _unavailable_entry(unavailable)))
            continue
        items, entry = _target_items(signature, target.module, kind, shared=shared, clock=clock)
        lines.add(target.target_id, *items)
        entries.append((target, entry))
    lines.add(None, "static TARGETS: &[cs_runner::Target] = &[")
    for target, entry in entries:
        lines.add(
            target.target_id,
            f"{INDENT}cs_runner::Target {{",
            f"{INDENT * 2}id: {rust_string(target.target_id)},",
            f"{INDENT * 2}file: {rust_string(target.trace_file)},",
            f"{INDENT * 2}entry: {entry},",
            f"{INDENT}}},",
        )
    lines.add(None, "];", "", "fn main() {", f"{INDENT}cs_runner::main(TARGETS)", "}")
    return Bridge("\n".join(lines.text) + "\n", dict(lines.owners), dict(lines.modules))


def unsupported_reason(signature: Signature, kind: ProblemKind) -> str | None:
    """Why no target of `signature` can run in Rust, or None."""
    if names_list_nodes(signature):
        return LIST_IDENTITY
    if kind is ProblemKind.CONCURRENT and node_kinds(signature):
        return SHARED_NODES_REASON
    return None


def rust_string(text: str) -> str:
    """A Rust string literal."""
    escaped: list[str] = []
    for character in text:
        match character:
            case "\\" | '"':
                escaped.append(f"\\{character}")
            case "\n":
                escaped.append("\\n")
            case "\t":
                escaped.append("\\t")
            case "\r":
                escaped.append("\\r")
            case _ if ord(character) < 0x20:
                escaped.append(f"\\u{{{ord(character):x}}}")
            case _:
                escaped.append(character)
    return '"' + "".join(escaped) + '"'


@dataclass
class _Lines:
    text: list[str] = field(default_factory=list[str])
    owners: dict[int, str] = field(default_factory=dict[int, str])
    modules: dict[int, str] = field(default_factory=dict[int, str])

    def add(self, owner: str | None, *lines: str) -> None:
        for line in lines:
            self.text.append(line)
            if owner is not None:
                self.owners[len(self.text)] = owner

    def module(self, owner: str, line: str) -> None:
        self.add(owner, line)
        self.modules[len(self.text)] = owner


def _imports(signature: Signature) -> list[str]:
    crates = crate_imports(signature)
    if not crates:
        return []
    standard = ["use std::cell::RefCell;", "use std::rc::Rc;", ""] if node_kinds(signature) else []
    return [*standard, *crates, ""]


def _unavailable_entry(unavailable: Unavailable) -> str:
    return (
        f"cs_runner::Entry::Unavailable {{ error_type: {rust_string(unavailable.error_type)}, "
        f"message: {rust_string(unavailable.message)} }}"
    )


@dataclass(frozen=True, slots=True)
class _ClassForm:
    """How a class reaches the runner: owned by one case, or shared by the worker threads of a
    concurrent problem."""

    construct: str
    wrap: str
    method: str
    receiver: str
    instance: str
    entry: str


_OWNED = _ClassForm(
    construct="cs_runner::Construct",
    wrap="cs_runner::object",
    method="cs_runner::Method",
    receiver="object: &mut dyn std::any::Any",
    instance="cs_runner::instance",
    entry="Class",
)
_SHARED = _ClassForm(
    construct="cs_runner::SharedConstruct",
    wrap="cs_runner::shared",
    method="cs_runner::SharedMethod",
    receiver="object: &(dyn std::any::Any + Send + Sync)",
    instance="cs_runner::shared_instance",
    entry="Concurrent",
)


def _target_items(
    signature: Signature, module: str, kind: ProblemKind, *, shared: bool, clock: bool
) -> tuple[list[str], str]:
    """The bridge functions of one target and its `Entry`."""
    if isinstance(signature, FunctionSignature):
        name = rust_name(signature.name, NameRole.FUNCTION)
        call = f"{module}::{name}"
        body = _call(signature.params, signature.returns, call, None)
        items = [
            f"fn {module}_call(args: &cs_runner::Args) -> "
            "Result<cs_runner::Call, cs_runner::InputError> {",
            *body.decoding,
            f"{INDENT}Ok(Box::new(move || {{",
            *body.calling(INDENT * 2),
            f"{INDENT}}}))",
            "}",
            "",
        ]
        return items, f"cs_runner::Entry::Function({module}_call)"
    form = _SHARED if kind is ProblemKind.CONCURRENT or shared else _OWNED
    if clock:
        return _clock_items(signature, module, form)
    return _class_items(signature, module, form)


def _class_items(signature: ClassSignature, module: str, form: _ClassForm) -> tuple[list[str], str]:
    entry = (
        f"cs_runner::Entry::{form.entry}(cs_runner::{form.entry} {{ "
        f"name: {rust_string(signature.name)}, "
        f"construct: {module}_construct, method: {module}_method }})"
    )
    return [
        *_construct_items(signature, module, form),
        *_method_items(signature, module, form),
    ], entry


def _construct_items(signature: ClassSignature, module: str, form: _ClassForm) -> list[str]:
    class_type = f"{module}::{signature.name}"
    constructor = _decoding(signature.constructor_params, None, signature.name)
    return [
        f"fn {module}_construct(args: &cs_runner::Args) -> "
        f"Result<{form.construct}, cs_runner::InputError> {{",
        *constructor,
        f"{INDENT}Ok(Box::new(move || {{",
        f"{INDENT * 2}let instance: {class_type} = "
        f"{class_type}::new({_arguments(signature.constructor_params, None)});",
        f"{INDENT * 2}{form.wrap}(instance)",
        f"{INDENT}}}))",
        "}",
        "",
    ]


def _method_items(signature: ClassSignature, module: str, form: _ClassForm) -> list[str]:
    """The `match` on the operation name, each arm a call on the instance; an `async fn` blocks
    the calling thread, a stress worker's, on the real clock."""
    class_type = f"{module}::{signature.name}"
    arms: list[str] = []
    for method in signature.methods:
        name = rust_name(method.name, NameRole.METHOD)
        body = _call(method.params, method.returns, f"instance.{name}", method.name)
        if method.is_async:
            body = replace(body, call=f"cs_runner::block_on({body.call})")
        arms += [
            f"{INDENT * 2}{rust_string(method.name)} => {{",
            *(f"{INDENT * 2}{line}" for line in body.decoding),
            f"{INDENT * 3}Ok(Box::new(move |{form.receiver}| {{",
            f"{INDENT * 4}let instance = {form.instance}::<{class_type}>(object);",
            *body.calling(INDENT * 4),
            f"{INDENT * 3}}}))",
            f"{INDENT * 2}}}",
        ]
    return _match(f"{module}_method", form.method, arms)


def _match(function: str, returned: str, arms: list[str]) -> list[str]:
    return [
        f"fn {function}(op: &str, args: &cs_runner::Args) -> "
        f"Result<{returned}, cs_runner::InputError> {{",
        f"{INDENT}match op {{",
        *arms,
        f"{INDENT * 2}_ => Err(cs_runner::InputError::unknown_op(op)),",
        f"{INDENT}}}",
        "}",
        "",
    ]


def _clock_items(signature: ClassSignature, module: str, form: _ClassForm) -> tuple[list[str], str]:
    """The constructor, the calls the runner awaits on a case's runtime, and for a shared
    instance the methods its stress workers call."""
    name = rust_string(signature.name)
    construct = _construct_items(signature, module, form)
    if form is _OWNED:
        entry = (
            f"cs_runner::Entry::Clock(cs_runner::ClockClass::Owned {{ name: {name}, "
            f"construct: {module}_construct, call: {module}_call }})"
        )
        return [*construct, *_clock_calls(signature, module, _OWNED_CALL)], entry
    entry = (
        "cs_runner::Entry::Clock(cs_runner::ClockClass::Shared { class: "
        f"cs_runner::Concurrent {{ name: {name}, construct: {module}_construct, "
        f"method: {module}_method }}, call: {module}_call }})"
    )
    stress = _method_items(signature, module, form)
    return [*construct, *stress, *_clock_calls(signature, module, _SHARED_CALL)], entry


_CLASS_TYPE = "{class_type}"
"""Stands for the entry class in a `_ClockForm`'s lines."""


@dataclass(frozen=True, slots=True)
class _ClockForm:
    """How an operation's call on the virtual clock reaches the runner: a future that borrows an
    owned instance, or one that holds a shared instance and whose result a task can hand back."""

    call: str
    """The type of the boxed call."""
    opening: tuple[str, ...]
    """The lines that open the call, indented relative to it, with `_CLASS_TYPE` for the entry
    class; the last line's indentation is the future's body's."""
    result: str
    """The future's last statement, which boxes the output."""
    closing: tuple[str, ...]


_OWNED_CALL = _ClockForm(
    "cs_runner::OwnedCall",
    (
        "Ok(cs_runner::owned_call(move |object| {",
        f"{INDENT}Box::pin(async move {{",
        f"{INDENT * 2}let instance = cs_runner::instance::<{_CLASS_TYPE}>(object);",
    ),
    "cs_runner::output(output)",
    (f"{INDENT}}})", "}))"),
)
_SHARED_CALL = _ClockForm(
    "cs_runner::SharedCall",
    (
        "Ok(cs_runner::shared_call(move |object| async move {",
        f"{INDENT}let instance = cs_runner::shared_instance::<{_CLASS_TYPE}>(&*object);",
    ),
    "cs_runner::sendable(output)",
    ("}))",),
)


def _clock_calls(signature: ClassSignature, module: str, form: _ClockForm) -> list[str]:
    """Each operation's call as a future: an `async fn` awaited, any other method called."""
    class_type = f"{module}::{signature.name}"
    arm = INDENT * 3
    body = arm + form.opening[-1][: len(form.opening[-1]) - len(form.opening[-1].lstrip())]
    arms: list[str] = []
    for method in signature.methods:
        name = rust_name(method.name, NameRole.METHOD)
        call = _call(method.params, method.returns, f"instance.{name}", method.name)
        awaited = f"{call.call}.await" if method.is_async else call.call
        arms += [
            f"{INDENT * 2}{rust_string(method.name)} => {{",
            *(f"{INDENT * 2}{line}" for line in call.decoding),
            *(f"{arm}{line.replace(_CLASS_TYPE, class_type)}" for line in form.opening),
            f"{body}let output: {call.output_type} = {awaited};",
            f"{body}{form.result}",
            *(f"{arm}{line}" for line in form.closing),
            f"{INDENT * 2}}}",
        ]
    return _match(f"{module}_call", form.call, arms)


@dataclass(frozen=True, slots=True)
class _Body:
    """One call: the statements that decode its arguments, inside the bridge function, and the
    statements inside the boxed closure that call the code and box the result."""

    decoding: list[str]
    call: str
    output_type: str
    result: str

    def calling(self, indent: str) -> list[str]:
        return [
            f"{indent}let output: {self.output_type} = {self.call};",
            f"{indent}cs_runner::output({self.result})",
        ]


def _call(params: Sequence[Param], returns: Returns, function: str, op: str | None) -> _Body:
    """A function's (`op` None) or a method's call, with the return modifiers applied
    (docs/specs/runners.md#node-modifiers)."""
    decoding = _decoding(params, returns.output_from, op)
    identity = returns.index_of or returns.no_alias_with
    call = f"{function}({_arguments(params, returns.output_from)})"
    if identity:
        nodes = f"{_IDENTITY_PREFIX}{_local(identity)}"
        decoding.append(f"{INDENT}let {nodes} = cs_runner::Identity::of(&{_argument(identity)});")
        call = f"cs_runner::retaining(|| {call})"
    return _Body(decoding, call, rust_type(returns.type) or "()", _result(returns))


def _result(returns: Returns) -> str:
    """The value to encode: the result, the `output_from` argument, or a modifier's wrapper."""
    if returns.output_from:
        return _argument(returns.output_from)
    if returns.serialize_as is NodeSerialization.VALUE:
        return "cs_runner::ValueOf(output)"
    if returns.index_of:
        nodes = f"{_IDENTITY_PREFIX}{_local(returns.index_of)}"
        return f"cs_runner::IndexIn::new(output, {nodes}, {rust_string(returns.index_of)})"
    if returns.no_alias_with:
        nodes = f"{_IDENTITY_PREFIX}{_local(returns.no_alias_with)}"
        return f"cs_runner::NoAlias::new(output, {nodes}, {rust_string(returns.no_alias_with)})"
    return "output"


def _decoding(params: Sequence[Param], output_from: str | None, op: str | None) -> list[str]:
    """Decodes every argument, by name for a function and by position for a constructor or a
    method (`op`); `ref_of` arguments come last because they point into another argument."""
    lines = [] if op is None else [f"{INDENT}args.count({len(params)}, {rust_string(op)})?;"]
    indexed = list(enumerate(params))
    ordered = [*(p for p in indexed if not p[1].ref_of), *(p for p in indexed if p[1].ref_of)]
    for index, param in ordered:
        mutable = "mut " if param.name == output_from else ""
        local = f"{mutable}{_argument(param.name)}: {rust_type(param.type)}"
        name = rust_string(param.name)
        if param.ref_of:
            within = f"&{_argument(param.ref_of)}, {rust_string(param.ref_of)}"
            lines.append(f"{INDENT}let {local} = args.node_in({index}, {name}, {within})?;")
        elif op is None:
            lines.append(f"{INDENT}let {local} = args.named({name})?;")
        else:
            lines.append(f"{INDENT}let {local} = args.at({index}, {name})?;")
    return lines


def _arguments(params: Sequence[Param], output_from: str | None) -> str:
    return ", ".join(
        f"&mut {_argument(param.name)}" if param.name == output_from else _argument(param.name)
        for param in params
    )


def _argument(canonical: str) -> str:
    return f"{ARGUMENT_PREFIX}{_local(canonical)}"


def _local(canonical: str) -> str:
    return member_name(canonical, Language.RUST, NameRole.PARAMETER)
